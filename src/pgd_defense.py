"""Standard PGD adversarial training (Madry et al., 2018) - the field's
baseline, well-proven defense method, used here instead of retrying the
from-scratch Stackelberg-VAE defense that failed three times (diagnosed
as gradient masking: it reduced vulnerability to the specific attack it
trained against while a different, black-box attack's success rate
stayed just as high or got worse).

Methodology, and why it should avoid the same trap:
- Train directly against real adversarial examples generated by PGD each
  batch (not a learned attacker model), so there's no separate "attacker
  network" whose own weaknesses the defense could be overfitting to.
- Evaluate against TWO different attacks, not just the one trained
  against: white-box PGD (matches training) and a black-box TRANSFER
  attack (adversarial examples crafted on an independently-trained
  undefended model, then tested on the defended one). This transfer-
  attack check is one of the standard sanity checks from Athalye et al.
  2018 ("Obfuscated Gradients Give a False Sense of Security") for
  catching gradient masking - if a defense only resists attacks crafted
  directly on itself, that's the same failure mode as before in disguise.
"""
import json
import os
import time

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

from data import load_fashion_mnist, CLASSES
from models import ProductCNN

RESULTS = "../results_pgd"
os.makedirs(RESULTS, exist_ok=True)
torch.manual_seed(0)

EPS = 0.1          # L-infinity perturbation budget (standard for 28x28 grayscale, [0,1] pixel range)
PGD_STEPS = 7       # PGD-7, a standard practical budget (Madry et al. used 40 for MNIST; 7-10 is the
ALPHA = 0.02        # common faster/practical variant, e.g. Zhang et al. TRADES uses similar budgets)
BATCH = 128
EPOCHS = 15


def pgd_attack(model, x, y, eps=EPS, alpha=ALPHA, steps=PGD_STEPS):
    """Untargeted PGD: maximize the model's loss within an L-inf ball of
    radius eps around x, projecting back into the ball and into [0,1]
    pixel range after every step - the standard formulation."""
    x_orig = x.clone().detach()
    delta = torch.empty_like(x).uniform_(-eps, eps)
    x_adv = torch.clamp(x_orig + delta, 0, 1).detach()

    for _ in range(steps):
        x_adv.requires_grad_(True)
        logits = model(x_adv)
        loss = F.cross_entropy(logits, y)
        grad = torch.autograd.grad(loss, x_adv)[0]
        x_adv = x_adv.detach() + alpha * grad.sign()
        x_adv = torch.max(torch.min(x_adv, x_orig + eps), x_orig - eps)
        x_adv = torch.clamp(x_adv, 0, 1).detach()
    return x_adv


def evaluate_clean(model, X, y, bs=512):
    model.eval()
    correct = 0
    with torch.no_grad():
        for i in range(0, len(X), bs):
            xb = torch.tensor(X[i:i+bs])
            yb = torch.tensor(y[i:i+bs])
            pred = model(xb).argmax(-1)
            correct += (pred == yb).sum().item()
    return correct / len(X)


def evaluate_attack_success(model, X, y, attack_fn, n=1000, bs=200, seed=0):
    """Fraction of correctly-classified examples that FLIP to a wrong
    prediction after the attack - the standard attack-success-rate metric
    (only meaningful on examples the model got right to begin with)."""
    rng = np.random.default_rng(seed)
    idx = rng.choice(len(X), size=min(n, len(X)), replace=False)
    model.eval()
    flipped, base_correct = 0, 0
    for i in range(0, len(idx), bs):
        b = idx[i:i+bs]
        xb = torch.tensor(X[b])
        yb = torch.tensor(y[b])
        with torch.no_grad():
            pred0 = model(xb).argmax(-1)
        correct_mask = pred0 == yb
        if correct_mask.sum() == 0:
            continue
        xb_c, yb_c = xb[correct_mask], yb[correct_mask]
        x_adv = attack_fn(xb_c, yb_c)
        with torch.no_grad():
            pred_adv = model(x_adv).argmax(-1)
        flipped += (pred_adv != yb_c).sum().item()
        base_correct += correct_mask.sum().item()
    return flipped / max(base_correct, 1)


def train_model(X, y, Xval, yval, adversarial, epochs=EPOCHS, tag=""):
    model = ProductCNN()
    opt = torch.optim.Adam(model.parameters(), lr=1e-3)
    n = len(X)
    t0 = time.time()
    for ep in range(epochs):
        model.train()
        idx = np.random.permutation(n)
        tot_loss = 0.0
        for i in range(0, n, BATCH):
            b = idx[i:i+BATCH]
            xb = torch.tensor(X[b])
            yb = torch.tensor(y[b])
            if adversarial:
                model.eval()
                xb_input = pgd_attack(model, xb, yb)
                model.train()
            else:
                xb_input = xb
            logits = model(xb_input)
            loss = F.cross_entropy(logits, yb)
            opt.zero_grad()
            loss.backward()
            opt.step()
            tot_loss += loss.item() * len(b)
        val_acc = evaluate_clean(model, Xval, yval)
        print(f"  [{tag}] epoch {ep+1}/{epochs}  train_loss={tot_loss/n:.4f}  val_clean_acc={val_acc:.4f}  "
              f"elapsed={time.time()-t0:.0f}s")
    return model


def main():
    Xtr, ytr, Xte, yte = load_fashion_mnist()
    # held-out validation slice from train, test set stays untouched until final eval
    n_val = 5000
    Xval, yval = Xtr[-n_val:], ytr[-n_val:]
    Xtr, ytr = Xtr[:-n_val], ytr[:-n_val]
    print(f"train={len(Xtr)} val={len(Xval)} test={len(Xte)}")

    undef_path = f"{RESULTS}/undefended.pt"
    if os.path.exists(undef_path):
        print("found undefended.pt, loading")
        undefended = ProductCNN()
        undefended.load_state_dict(torch.load(undef_path))
    else:
        print("training undefended baseline...")
        undefended = train_model(Xtr, ytr, Xval, yval, adversarial=False, epochs=EPOCHS, tag="undefended")
        torch.save(undefended.state_dict(), undef_path)

    pgd_path = f"{RESULTS}/pgd_defended.pt"
    if os.path.exists(pgd_path):
        print("found pgd_defended.pt, loading")
        defended = ProductCNN()
        defended.load_state_dict(torch.load(pgd_path))
    else:
        print("training PGD-adversarially-trained model...")
        defended = train_model(Xtr, ytr, Xval, yval, adversarial=True, epochs=EPOCHS, tag="pgd_defended")
        torch.save(defended.state_dict(), pgd_path)

    # --- final evaluation on the untouched real test set ---
    def pgd_fn_for(model):
        return lambda x, y: pgd_attack(model, x, y)

    results = {}
    for name, model in [("undefended", undefended), ("pgd_defended", defended)]:
        clean_acc = evaluate_clean(model, Xte, yte)
        whitebox_pgd = evaluate_attack_success(model, Xte, yte, pgd_fn_for(model), n=1000, seed=1)
        # black-box transfer attack: craft on the UNDEFENDED model, evaluate on `model`
        transfer_attack = evaluate_attack_success(model, Xte, yte, pgd_fn_for(undefended), n=1000, seed=1)
        results[name] = {"clean_acc": clean_acc, "whitebox_pgd_success": whitebox_pgd,
                          "transfer_attack_success": transfer_attack}
        print(f"{name:14s} clean_acc={clean_acc:.4f}  whitebox_PGD_success={whitebox_pgd:.4f}  "
              f"transfer_attack_success={transfer_attack:.4f}")

    json.dump(results, open(f"{RESULTS}/final_results.json", "w"), indent=2)


if __name__ == "__main__":
    main()
